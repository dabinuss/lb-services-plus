const LanguageContext = createContext(null)

function initialLanguage() {
  const stored = window.localStorage?.getItem(STORAGE_KEY)
  if (stored === 'de' || stored === 'en') return stored
  return window.navigator?.language?.toLowerCase().startsWith('de') ? 'de' : 'en'
}

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(initialLanguage)

  useEffect(() => {
    document.documentElement.lang = language
  }, [language])

  const value = useMemo(() => {
    const setLanguage = (next) => {
      if (next !== 'de' && next !== 'en') return
      window.localStorage?.setItem(STORAGE_KEY, next)
      setLanguageState(next)
    }

    const t = (key, variables = {}) => {
      const template = language === 'de' ? (DE[key] ?? key) : key
      return Object.entries(variables).reduce(
        (text, [name, replacement]) => text.replaceAll(`{${name}}`, String(replacement)),
        template,
      )
    }

    const formatRelativeTime = (iso) => {
      const seconds = Math.max(0, Math.floor((Date.now() - new Date(iso).getTime()) / 1000))
      if (seconds < 60) return t('now')
      if (seconds < 3600) return t('{count}m', { count: Math.floor(seconds / 60) })
      if (seconds < 86400) return t('{count}h', { count: Math.floor(seconds / 3600) })
      return t('{count}d', { count: Math.floor(seconds / 86400) })
    }

    const formatDateTime = (value) => new Intl.DateTimeFormat(language === 'de' ? 'de-DE' : 'en-US', {
      dateStyle: 'short', timeStyle: 'short',
    }).format(new Date(value))

    return { language, setLanguage, t, formatRelativeTime, formatDateTime }
  }, [language])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useI18n() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useI18n must be used inside LanguageProvider')
  return context
}
