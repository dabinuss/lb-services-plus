import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const source = JSON.parse(await readFile(resolve(root, "shared/api_contracts.json"), "utf8"));
const table = (entries) => Object.entries(entries).map(([name, contract]) =>
  `| \`${name}\` | ${contract.input.map((field) => `\`${field}\``).join(", ") || "None"} | \`${contract.result}\` | \`${contract.rate}\` |`).join("\n");
const list = (values) => values.map((value) => `- \`${value}\``).join("\n");
const output = `# Generated API Contract Inventory

Generated from [\`shared/api_contracts.json\`](../../shared/api_contracts.json). Do not edit this file manually.

API version: \`${source.version}\`

## App Actions

| Name | Input fields | Result | Rate key |
| --- | --- | --- | --- |
${table(source.actions)}

## Trusted Exports

| Name | Input fields | Result | Rate key |
| --- | --- | --- | --- |
${table(source.exports)}

## Local Server Events

${list(source.serverEvents)}

## Push Messages

${list(source.pushMessages)}
`;

const target = resolve(root, "docs/api/CONTRACT_INVENTORY.md");
if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== output) throw new Error("Generated API contract inventory is out of date. Run npm run docs:generate.");
} else {
  await writeFile(target, output, "utf8");
}
